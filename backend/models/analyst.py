"""
Pydantic models for the Insight Analyst Agent.
Defines request and response schemas for deterministic research analysis.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class EvidenceObservation(BaseModel):
    """
    Evidence-backed observation linked directly to an eligible verified source.
    """
    statement: str = Field(
        ...,
        description="Factual observation derived strictly from verified source evidence"
    )
    source_title: str = Field(
        ...,
        description="Title of the source providing the evidence"
    )
    source_url: str = Field(
        ...,
        description="Direct URL to the source verifying this observation"
    )
    confidence: str = Field(
        default="high",
        description="Confidence assessment based on source verification status"
    )
    confidence_reason: Optional[str] = Field(
        default=None,
        description="Detailed justification for confidence level"
    )
    is_weakly_relevant: bool = Field(
        default=False,
        description="Flag indicating source was classified as weakly relevant"
    )
    source_name: str = Field(
        default="wikipedia",
        description="Provider name identifier ('wikipedia', 'arxiv', or 'crossref')"
    )
    source_type: str = Field(
        default="wikipedia_extract",
        description="Provenance classification for the source record"
    )
    publication_date: Optional[str] = Field(
        default=None,
        description="Publication date or year-month when available"
    )
    doi: Optional[str] = Field(
        default=None,
        description="Digital Object Identifier (DOI) when available"
    )
    authors: List[str] = Field(
        default_factory=list,
        description="List of contributing authors when available"
    )


class KeyTheme(BaseModel):
    """
    Topical theme grouped across multiple research results.
    """
    theme: str = Field(
        ...,
        description="Name or categorization label for the identified theme"
    )
    description: str = Field(
        ...,
        description="Summary explanation of the theme derived from evidence snippets"
    )
    frequency: int = Field(
        ...,
        ge=1,
        description="Number of verified sources contributing to this theme"
    )
    sources: List[str] = Field(
        default_factory=list,
        description="List of supporting source URLs for this theme"
    )


class AnalysisRequest(BaseModel):
    """
    Request model for the Insight Analyst Agent.
    Requires structured research data and its corresponding verification report.
    """
    research: Dict[str, Any] = Field(
        ...,
        description="Structured research data collected by the Data Collector Agent"
    )
    verification: Dict[str, Any] = Field(
        ...,
        description="Verification report generated by the Research Verification Agent"
    )

    @field_validator("research")
    @classmethod
    def validate_research(cls, v: Dict[str, Any]) -> Dict[str, Any]:
        """Validate research payload structure and size bounds."""
        if not isinstance(v, dict):
            raise ValueError("Research payload must be a dictionary object")
        if "query" not in v:
            raise ValueError("Research payload missing required 'query' field")
        query_str = str(v.get("query", ""))
        if len(query_str) > 300:
            raise ValueError("Research query exceeds maximum permitted length of 300 characters")
        results = v.get("results")
        if results is not None and not isinstance(results, list):
            raise ValueError("Research 'results' must be a list")
        if isinstance(results, list) and len(results) > 50:
            raise ValueError("Research results exceed maximum allowed batch size of 50 items")
        return v

    @field_validator("verification")
    @classmethod
    def validate_verification(cls, v: Dict[str, Any]) -> Dict[str, Any]:
        """Validate verification report payload structure and size bounds."""
        if not isinstance(v, dict):
            raise ValueError("Verification payload must be a dictionary object")
        if "query" not in v:
            raise ValueError("Verification payload missing required 'query' field")
        query_str = str(v.get("query", ""))
        if len(query_str) > 300:
            raise ValueError("Verification query exceeds maximum permitted length of 300 characters")
        results = v.get("results")
        if results is not None and not isinstance(results, list):
            raise ValueError("Verification 'results' must be a list")
        if isinstance(results, list) and len(results) > 50:
            raise ValueError("Verification results exceed maximum allowed batch size of 50 items")
        return v


class AnalysisResponse(BaseModel):
    """
    Comprehensive structured analysis produced by the Insight Analyst Agent.
    """
    agent: str = Field(
        default="Insight Analyst Agent",
        description="Name of the agent responsible for the analysis"
    )
    agent_name: str = Field(
        default="Insight Analyst Agent",
        description="Canonical agent name identifier"
    )
    topic: str = Field(
        ...,
        description="Research topic or search query analyzed"
    )
    analyzed_at: str = Field(
        ...,
        description="ISO 8601 UTC timestamp of analysis execution"
    )
    total_sources_evaluated: int = Field(
        ...,
        ge=0,
        description="Total source records provided in the research batch"
    )
    eligible_sources_count: int = Field(
        ...,
        ge=0,
        description="Count of sources meeting all verification criteria"
    )
    excluded_sources_count: int = Field(
        ...,
        ge=0,
        description="Count of sources excluded due to failed checks or duplication"
    )
    source_distribution: Dict[str, int] = Field(
        default_factory=dict,
        description="Distribution count of eligible verified sources grouped by provider"
    )
    executive_summary: str = Field(
        ...,
        description="High-level narrative summary of findings derived from eligible evidence"
    )
    key_themes: List[KeyTheme] = Field(
        default_factory=list,
        description="Topical themes identified across eligible evidence"
    )
    important_keywords: List[str] = Field(
        default_factory=list,
        description="Important keywords extracted from eligible evidence"
    )
    evidence_backed_observations: List[EvidenceObservation] = Field(
        default_factory=list,
        description="Evidence-backed observations with direct source attribution"
    )
    information_gaps: List[str] = Field(
        default_factory=list,
        description="Identified gaps or missing context in the evidence base"
    )
    recommendations: List[str] = Field(
        default_factory=list,
        description="Actionable next-step recommendations"
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Methodological limitations and boundaries of this analysis"
    )
    methodology: str = Field(
        default="Deterministic keyword extraction, frequency analysis, and rule-based theme clustering. No generative LLM extrapolation.",
        description="Explicit disclosure of the deterministic analysis methodology"
    )

